local setup = require('setup')

test('set saves, takes any key case and multi-word values', function(m, t)
    setup.items(m)
    m.start()
    m.command('/bogoswap set triggereffectname Spirit of Wolf')
    m.command('/bogoswap set MatchItemName "Fine Steel Sword"')
    m.command('/bogoswap set SwapEquipmentSlot Primary')
    local cfg = setup.readConfig(m)
    t.eq(cfg.TriggerEffectName, 'Spirit of Wolf')
    t.eq(cfg.MatchItemName, 'Fine Steel Sword')
    t.eq(cfg.SwapEquipmentSlot, 'mainhand', 'alias')
    m.command('/bogoswap set MatchItemName')
    t.eq(setup.readConfig(m).MatchItemName, '', 'cleared')
end)

test('set rejects unknown keys and slots', function(m, t)
    m.start()
    m.command('/bogoswap set Colour red')
    t.contains(m.output(), 'Unknown setting "Colour"')
    m.command('/bogoswap set SwapEquipmentSlot elbow')
    t.contains(m.output(), 'Unknown slot "elbow"')
    t.eq(setup.readConfig(m).SwapEquipmentSlot, '')
end)

test("set warns when an item can't be worn in the slot", function(m, t)
    setup.swords(m)
    m.world.bags = { 'Lucky Charm' }
    m.start()
    m.command('/bogoswap set NoMatchItemName Lucky Charm')
    t.contains(m.output(), "NoMatchItemName 'Lucky Charm' can't be worn in mainhand")
    t.eq(setup.readConfig(m).NoMatchItemName, 'Lucky Charm', 'still saved')
end)

test('pause, resume and toggle', function(m, t)
    setup.swords(m)
    m.start()
    m.command('/bogoswap pause')
    t.contains(m.output(), 'Already paused.')
    m.command('/bogoswap resume')
    t.contains(m.output(), 'Resumed.')
    m.run(1000)
    t.eq(#m.cmds, 1)
    m.command('/bswap toggle')
    t.contains(m.output(), 'Paused. Watching, but taking no action.')
    m.world.buffs = { 'Spirit of Wolf' }
    m.run(1000)
    t.eq(#m.cmds, 1, 'paused via alias')
end)

test('debug channels switch and persist', function(m, t)
    m.start()
    m.command('/bogoswap debug all on')
    local d = setup.readConfig(m).Debug
    t.ok(d.swap and d.guard and d.config and d.cmd and d.ui, 'all on')
    m.command('/bogoswap debug guard off')
    t.eq(setup.readConfig(m).Debug.guard, false)
    m.command('/bogoswap debug elbow on')
    t.contains(m.output(), 'Unknown debug channel "elbow"')
    m.command('/bogoswap debug')
    t.contains(m.output(), 'On: swap, config, cmd, ui')
end)

test('show and help', function(m, t)
    setup.swords(m)
    m.start()
    m.run(500)
    m.command('/bogoswap show')
    local out = m.output()
    t.contains(out, 'PAUSED')
    t.contains(out, 'TriggerEffectName = "Spirit of Wolf"')
    t.contains(out, 'Status: paused;')
    t.contains(out, 'Config file:')
    m.command('/bogoswap help')
    t.contains(m.output(), 'swapnow')
    m.command('/bogoswap frobnicate')
    t.contains(m.output(), 'Unknown command "frobnicate"')
end)

test('ui command shows and hides the window', function(m, t)
    m.start()
    m.command('/bogoswap ui')
    m.frame()
    t.eq(#m.ui.calls, 0, 'hidden')
    m.command('/bogoswap ui on')
    m.frame()
    t.ok(#m.ui.calls > 0, 'shown')
end)

test('quit stops the script and removes binds and the TLO', function(m, t)
    m.start()
    t.ok(m.binds['/bogoswap'] and m.tlos.BogoSwap, 'registered')
    m.command('/bogoswap quit')
    m.step(2)
    t.ok(m.finished)
    t.eq(m.binds['/bogoswap'], nil)
    t.eq(m.binds['/bswap'], nil)
    t.eq(m.tlos.BogoSwap, nil)
    t.contains(m.output(), 'Stopped.')
end)
