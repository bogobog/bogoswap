test('action numbers increase and lines share them', function(m, t)
    local log = require('bogoswap.core.log')
    log.setChannel('swap', true)
    local a = log.nextAction()
    log.debug('swap', a, 'first')
    log.debug('swap', a, 'still first')
    local b = log.nextAction()
    t.eq(b, a + 1)
    local out = m.output()
    t.contains(out, '#' .. a .. ' swap first')
    t.contains(out, '#' .. a .. ' swap still first')
end)

test('disabled channels are silent; unknown channels are an error', function(m, t)
    local log = require('bogoswap.core.log')
    log.debug('guard', log.nextAction(), 'hidden')
    t.eq(m.output(), '')
    t.raises(function() log.debug('nope', 1, 'x') end, 'unknown log channel')
end)

test('note logs only when the message changes', function(m, t)
    local log = require('bogoswap.core.log')
    log.setChannel('guard', true)
    log.note('k', 'guard', nil, 'casting')
    log.note('k', 'guard', nil, 'casting')
    log.note('k', 'guard', nil, 'stunned')
    log.note('k', 'guard', nil, 'casting')
    local _, n = m.output():gsub('casting', '')
    t.eq(n, 2)
    log.resetNote('k')
    log.note('k', 'guard', nil, 'casting')
    _, n = m.output():gsub('casting', '')
    t.eq(n, 3)
end)

test('messages with % are safe', function(m, t)
    local log = require('bogoswap.core.log')
    log.info('100% sure')
    log.info('%s', '50% sure')
    t.contains(m.output(), '100% sure')
    t.contains(m.output(), '50% sure')
end)

test('debug lines start with the time they were emitted', function(m, t)
    local log = require('bogoswap.core.log')
    log.setChannel('swap', true)
    log.debug('swap', log.nextAction(), 'stamped')
    m.now = m.now + 61000
    log.info('not stamped')
    log.debug('swap', log.nextAction(), 'later')
    local out = m.output()
    t.contains(out, '[00:16:40] [BogoSwap] #1 swap stamped')
    t.contains(out, '[00:17:41] [BogoSwap] #2 swap later')
    t.contains(out, '\n[BogoSwap] not stamped')
end)
